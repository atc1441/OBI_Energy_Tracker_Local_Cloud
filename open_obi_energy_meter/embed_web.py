"""Embed deterministic gzip pages during the build."""

import gzip
import io
from pathlib import Path


def generate(source, destination):
    lines = ['// Generated by embed_web.py.', '#pragma once',
             '#include <stdint.h>', '#include <pgmspace.h>']
    pages = sorted(Path(source).glob('*.html'))
    if not pages:
        raise ValueError('No web pages found')
    for page in pages:
        buffer = io.BytesIO()
        with gzip.GzipFile(fileobj=buffer, filename='', mode='wb', mtime=0) as stream:
            stream.write(page.read_bytes())
        data = buffer.getvalue()
        symbol = page.stem.upper() + '_HTML_GZ'
        lines.append(f'static const uint8_t {symbol}[] PROGMEM = {{')
        for offset in range(0, len(data), 16):
            lines.append('  ' + ','.join(f'0x{byte:02x}' for byte in data[offset:offset + 16]) + ',')
        lines.append('};')
    output = '\n'.join(lines) + '\n'
    destination = Path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    if not destination.exists() or destination.read_text() != output:
        destination.write_text(output)


if 'Import' in globals():
    Import('env')  # noqa: F821
    generated = Path(env.subst('$BUILD_DIR')) / 'generated'  # noqa: F821
    generate(Path(env['PROJECT_DIR']) / 'web', generated / 'web_assets.h')  # noqa: F821
    env.Append(CPPPATH=[str(generated)])  # noqa: F821
elif __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path)
    parser.add_argument('destination', type=Path)
    arguments = parser.parse_args()
    generate(arguments.source, arguments.destination)

// Remove a reader's discovery entities from HA by publishing empty retained configs, and drop its retained
// availability so a deleted reader leaves nothing behind on the broker.
// Mirrors the topics created by publishDiscovery() — keep the two lists in sync.
static void clearDiscovery(const String &id) {
  String uid = "obi_" + id;
  static const char *sensors[]  = {"import","export","power","power_calc","battery","rssi","snr","lastseen","id","uuid","type","firmware","hardware"};
  static const char *binaries[] = {"infrared","paired","legacy","bootloader"};
  for (const char *k : sensors)  { String t = "homeassistant/sensor/"        + uid + "/" + k + "/config"; mqtt.publish(t.c_str(), "", true); }
  for (const char *k : binaries) { String t = "homeassistant/binary_sensor/" + uid + "/" + k + "/config"; mqtt.publish(t.c_str(), "", true); }
  String t = "homeassistant/number/" + uid + "/interval/config"; mqtt.publish(t.c_str(), "", true);
  String ts = "homeassistant/select/" + uid + "/interval_preset/config"; mqtt.publish(ts.c_str(), "", true);
  mqtt.publish(rdrAvtTopic(id).c_str(), "", true);   // clear the retained online/offline flag as well
}

// Web button: drop a (phantom) reader from the list. Not a permanent block — the next valid
// frame re-creates it. Also clears its HA discovery so a phantom doesn't linger in Home Assistant.
static void handleDelete() {
  String id = server.arg("id");
  if (id.length() != 6) { server.send(400, "application/json", "{\"ok\":false}"); return; }
  uint8_t h[3];
  for (int i = 0; i < 3; i++) h[i] = (uint8_t)strtol(id.substring(i * 2, i * 2 + 2).c_str(), nullptr, 16);
  bool ok = gw_delete_reader(h);
  if (ok && mqtt.connected()) clearDiscovery(id);
  server.send(200, "application/json", ok ? "{\"ok\":true}" : "{\"ok\":false}");
}

// Web button: force a fresh discovery + availability publish for every known reader.
static void handleRediscover() {
  if (!mqtt.connected()) { server.send(200, "application/json", "{\"ok\":false}"); return; }
  mqtt.publish(avtTopic().c_str(), "online", true);
  publishGatewayDiscovery();
  int n = 0;
  for (int i = 0; i < MAX_READERS; i++) {
    Reader &r = readers[i];
    if (r.used && r.haveData) { publishDiscovery(r); r.mqttDiscovered = true; r.mqttAvail = -1; n++; }
  }
  // -1 above: mqttService() re-publishes each reader's current online/offline on its next pass, so the
  // freshly (re)created entities immediately get an availability state instead of waiting for a change.
  server.send(200, "application/json", String("{\"ok\":true,\"count\":") + n + "}");
}

static void mqttService() {
  if (g_ghState == 1) return;          // a GitHub OTA download is running — don't fight it for CPU/heap/TLS
  static uint32_t lastTry = 0, lastPub = 0;
  uint32_t now = millis();
  g_mqttState = mqtt.state();
  if (g_mqttHost[0] && !mqtt.connected() && (g_mqttReconnect || now - lastTry > 8000)) {
    g_mqttReconnect = false;
    lastTry = now;
    String cid = "obi-gw-" + String(gwId());                    // unique client id per gateway
    String avt = avtTopic();                                    // per-gateway availability (LWT) topic
    if (mqtt.connect(cid.c_str(), g_mqttUser[0] ? g_mqttUser : nullptr, g_mqttPass[0] ? g_mqttPass : nullptr,
                     avt.c_str(), 0, true, "offline")) {          // broker publishes "offline" if we drop
      String sub = String(g_mqttTopic) + "/+/set_interval";     // one wildcard level = reader id
      mqtt.subscribe(sub.c_str());
      mqtt.subscribe(rebootTopic().c_str());                    // <base>/gateway/<gwid>/reboot
      mqtt.subscribe(installTopic().c_str());                   // <base>/gateway/<gwid>/update/install
      mqtt.publish(avt.c_str(), "online", true);
      publishGatewayDiscovery();
      g_updPubDirty = true;                                     // (re)assert the update state, see below
      for (int i = 0; i < MAX_READERS; i++) { readers[i].mqttDiscovered = false;   // re-announce after (re)connect
                                              readers[i].mqttAvail = -1; }         // ...and re-assert online/offline
      Serial.printf("[mqtt] connected as %s, subscribed %s + reboot\n", cid.c_str(), sub.c_str());
    }
    g_mqttState = mqtt.state();
  }
  if (mqtt.connected()) {
    mqtt.loop();
    // HA update entity: "Install" (flagged by mqttCallback). Ignored unless a newer release is actually known --
    // HA itself only offers Install then, and this also keeps a stray retained "install" from re-flashing on
    // every reconnect. On success ghOtaTask() takes MQTT down right away, so leave this pass immediately.
    if (g_ghInstallReq) {
      g_ghInstallReq = false;
      if (g_ghLatestTag.length() && verNewer(g_ghLatestTag.c_str(), FW_VERSION)) {
        const char *err = ghStartOta();
        Serial.printf("[mqtt] rx update install -> %s\n", err ? err : "started");
        if (!err) return;
      } else Serial.println("[mqtt] rx update install ignored: no newer release known");
    }
    // Release check for the HA update entity's latest_version: one minute after the first connect, then every
    // g_ghIntervalH hours (the auto-update interval). Only a lookup -- installing stays with the user (or with
    // the auto-update loop, if they enabled it). A failed lookup retries after an hour.
    { static uint32_t relDueMs = 0; static bool relArmed = false;
      if (!relArmed) { relArmed = true; relDueMs = now + 60000UL; }
      if (!g_ftpBusy && (int32_t)(now - relDueMs) >= 0) {
        String tag, url;
        bool ok = githubLatest(tag, url) && url.length();
        relDueMs = millis() + (ok ? g_ghIntervalH * 3600000UL : 3600000UL);
        if (ok) ghNoteLatest(tag, url);
      } }
    if (g_updPubDirty) { g_updPubDirty = false; publishUpdateState(false); }
    // Gateway state (retained) — temp, uptime, heap, wifi rssi, reader counts; keyed by MAC via the topic.
    // Slow-moving, so it stays on the fixed g_pubEvery cadence and does NOT need to track the reader rate.
    // Two reader counts: readers_all = every reader we've heard (bound or greyed), readers_bound = only the
    // ones actually assigned/bound to THIS gateway. `readers` is kept = readers_all for backward compat.
    if (now - lastPub > (uint32_t)g_pubEvery * 1000) {
      lastPub = now;
      { int rcAll = 0, rcBound = 0;
        for (int i = 0; i < MAX_READERS; i++) if (readers[i].used) { rcAll++; if (readers[i].assigned) rcBound++; }
        float t = gwTempC();
        String gp = "{\"mac\":\"" + String(gwMac()) + "\",\"gw\":\"" + String(gwId()) + "\""
                    ",\"gw_name\":\"OBI Gateway " + String(gwId()) + "\"" +   // original/technical name -- ALWAYS sent, even after a custom rename (see publishGatewayDiscovery's "dev.name")
                    ",\"temp_c\":" + (isnan(t) ? String("null") : String(t, 1)) +
                    ",\"uptime_s\":" + String(gw_uptime_s()) +
                    ",\"heap_free\":" + String(ESP.getFreeHeap()) +
                    ",\"wifi_rssi\":" + String(WiFi.RSSI()) +
                    ",\"ip\":\"" + WiFi.localIP().toString() + "\"" +
                    ",\"readers\":" + String(rcAll) +
                    ",\"readers_all\":" + String(rcAll) +
                    ",\"readers_bound\":" + String(rcBound) +
                    ",\"auth_fail_count\":" + String(g_authFailCount) + "," + fwJson() + "}";
        if (mqtt.publish(gwStateTopic().c_str(), gp.c_str(), true)) { g_mqttPubCount++; g_mqttLastPubMs = now; } }
    }
    // Per-reader telemetry is EVENT-DRIVEN: publish the instant a fresh energy frame has been decoded
    // (lastEnergyMs is bumped by the LoRa task on every energy frame) instead of on the g_pubEvery timer,
    // so MQTT tracks the reader's own report interval and values reach the broker as soon as they arrive.
    // The reader's report interval is the natural rate limit, so no extra throttle is needed here.
    for (int i = 0; i < MAX_READERS; i++) {
      Reader &r = readers[i];
      if (!r.used || !r.haveData) continue;
      bool fresh = (r.lastEnergyMs != r.mqttPubEnergyMs);   // a new energy frame arrived since the last publish
      if (!r.mqttDiscovered && !fresh) continue;            // never announced and nothing new -> nothing to do
      if (!r.mqttDiscovered) { publishDiscovery(r); r.mqttDiscovered = true; r.mqttAvail = -1; }
      // Availability BEFORE the state publish: a reader coming back does both in this same pass, and HA only
      // shows a state it received while the entity was available. Costs nothing while unchanged (no String
      // is built), so this can run on every service pass — that's also what makes going offline timely.
      int8_t up = readerOnline(r) ? 1 : 0;
      if (r.mqttAvail != up) {
        String at = rdrAvtTopic(hex(r.handle, 3));
        if (mqtt.publish(at.c_str(), up ? "online" : "offline", true)) { g_mqttPubCount++; g_mqttLastPubMs = now; }
        r.mqttAvail = up;
        Serial.printf("[mqtt] reader %02X%02X%02X -> %s (unseen %lus)\n", r.handle[0], r.handle[1], r.handle[2],
                      up ? "online" : "offline", (unsigned long)((millis() - r.lastSeenMs) / 1000));
      }
      if (!fresh) continue;
      r.mqttPubEnergyMs = r.lastEnergyMs;
      String id = hex(r.handle, 3);
      String topic = String(g_mqttTopic) + "/" + id;
      // "Today so far" (consumption/export/cost/earnings) and the current tariff zone/rate -- the same
      // numbers the History page's own KPIs show, computed here so HA gets them without a browser. Both
      // need a synced clock; today's stats also need a same-day "start of day" baseline (see haveStart in
      // DailyState/beginDay()) that a reader can lack for a while right after its very first observation.
      bool tv = timeValid();
      time_t tnow = tv ? time(nullptr) : 0;
      float todayWh = 0, todayExpWh = 0, todayCostEur = 0, todayEarnEur = 0;
      bool haveToday = tv && readerTodayStats(i, r, todayWh, todayExpWh, todayCostEur, todayEarnEur);
      // Built into one fixed stack buffer via snprintf, NOT chained String concatenation -- this publish
      // fires on every energy frame (as often as ~1/s for a live-interval reader), and this project has
      // already been bitten once by heap fragmentation from exactly this kind of repeated small-String
      // churn colliding with a concurrent GitHub-OTA download's own heap-hungry TLS handshake (confirmed
      // live: a real OTA test failed with "couldn't start the flash write, 7072 B free heap" while this
      // payload's earlier String-concatenation version was in place, publishing every second). A stack
      // buffer costs zero heap and creates zero fragmentation, however often this runs.
      char uuidBuf[42];
      if (r.haveUuid) { String u = uuidStr(r.uuid); snprintf(uuidBuf, sizeof uuidBuf, "\"%s\"", u.c_str()); }
      else strcpy(uuidBuf, "null");
      char impBuf[12], expBuf[12], pwBuf[12], pwcBuf[12];
      if (obi_na(r.import_))   strcpy(impBuf, "null"); else snprintf(impBuf, sizeof impBuf, "%lu", (unsigned long)r.import_);
      if (obi_na(r.export_))   strcpy(expBuf, "null"); else snprintf(expBuf, sizeof expBuf, "%lu", (unsigned long)r.export_);
      if (obi_na(r.power))     strcpy(pwBuf,  "null"); else snprintf(pwBuf,  sizeof pwBuf,  "%ld", (long)(int32_t)r.power);
      if (obi_na(r.calcPower)) strcpy(pwcBuf, "null"); else snprintf(pwcBuf, sizeof pwcBuf, "%ld", (long)(int32_t)r.calcPower);
      char todayWhBuf[12], todayExpBuf[12], todayCostBuf[16], todayEarnBuf[16], rateBuf[10];
      if (haveToday) {
        snprintf(todayWhBuf, sizeof todayWhBuf, "%lu", (unsigned long)todayWh);
        snprintf(todayExpBuf, sizeof todayExpBuf, "%lu", (unsigned long)todayExpWh);
        snprintf(todayCostBuf, sizeof todayCostBuf, "%.3f", (double)todayCostEur);
        snprintf(todayEarnBuf, sizeof todayEarnBuf, "%.3f", (double)todayEarnEur);
      } else {
        strcpy(todayWhBuf, "null"); strcpy(todayExpBuf, "null");
        strcpy(todayCostBuf, "null"); strcpy(todayEarnBuf, "null");
      }
      if (tv) snprintf(rateBuf, sizeof rateBuf, "%.2f", (double)tariffRateCentNow(r, tnow));
      else    strcpy(rateBuf, "null");
      char p[800];
      int n = snprintf(p, sizeof p,
        "{\"id\":\"%s\",\"uuid\":%s,\"type\":\"%s\",\"battery_mV\":%u,\"rssi\":%d,\"snr\":%.1f,"
        "\"infrared\":%s,\"import\":%s,\"export\":%s,\"power\":%s,\"power_calc\":%s,"
        "\"softver\":%u,\"hardver\":%u,\"paired\":%s,\"legacy\":%s,\"bootloader\":%s,"
        "\"interval\":%u,\"age_s\":%lu,"
        "\"today_wh\":%s,\"today_exp_wh\":%s,\"today_cost\":%s,\"today_earn\":%s,"
        "\"tariff_mode\":%u,\"tariff_zone\":\"%s\",\"tariff_rate_cent\":%s,"
        "\"day_wh\":%lu,\"night_wh\":%lu,\"ht_wh\":%lu,\"st_wh\":%lu,\"nt_wh\":%lu}",
        id.c_str(), uuidBuf, typeName(r.devType), r.battery_mV, (int)r.lastRssi, (double)r.lastSnr,
        (r.flags & 1) ? "true" : "false", impBuf, expBuf, pwBuf, pwcBuf,
        r.softver, r.hardver, r.haveKey ? "true" : "false", r.legacy ? "true" : "false",
        r.inBootloader ? "true" : "false",
        r.setInterval, (unsigned long)((millis() - r.lastSeenMs) / 1000),
        todayWhBuf, todayExpBuf, todayCostBuf, todayEarnBuf,
        r.tariffMode, tv ? tariffZoneName(r, tnow) : "n/a", rateBuf,
        (unsigned long)hDaily[i].dayWh, (unsigned long)hDaily[i].nightWh,
        (unsigned long)hDaily[i].htWh, (unsigned long)hDaily[i].stWh, (unsigned long)hDaily[i].ntWh);
      if (n > 0 && n < (int)sizeof p && mqtt.publish(topic.c_str(), p)) {
        g_mqttPubCount++; g_mqttLastPubMs = now;
      }
    }
  }
}


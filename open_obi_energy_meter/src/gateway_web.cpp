// Self-heals a corrupted system clock. esp_restart() (used by every self-OTA reboot on this device) does
// NOT reset the RTC-backed clock that time()/gettimeofday() read from -- only a full power-on reset does.
// So if a bad SNTP reply (or any other glitch) ever pushes the clock to an implausible value once, EVERY
// subsequent reboot inherits that same garbage value from boot #1, before syncNtp() even gets a chance to
// run again -- it doesn't just show up once, it sticks across reboots (observed: repeated back-to-back
// self-OTA reboots during dev testing left the clock reporting the year 343230). timeValid() already stops
// that garbage from being displayed/trusted (see its comment), but the underlying clock stays corrupted
// until a fresh sync happens to overwrite it -- which may not be for a while, since the built-in SNTP
// client re-polls on its own schedule (on the order of hours), not immediately. Resetting to epoch 0 here
// clears the bad value right away and kicks a fresh sync attempt, so the device recovers within seconds
// instead of silently reporting "not synced" indefinitely.
static void clampTimeSanity() {
  if (time(nullptr) < 4102444800) return;   // 2100-01-01 UTC — same bound as timeValid()
  struct timeval tv = {0, 0};
  settimeofday(&tv, nullptr);
  Serial.println("[time] system clock was implausibly far in the future -- reset to epoch 0, forcing NTP resync");
  if (WiFi.status() == WL_CONNECTED) syncNtp();
}


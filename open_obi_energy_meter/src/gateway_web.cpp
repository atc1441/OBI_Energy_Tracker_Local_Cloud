// Sanity-bounded: lower bound catches "never synced" (RTC still near the 1970 epoch); upper bound catches
// a garbage/corrupted SNTP reply being trusted as real (observed after rapid back-to-back self-OTA reboots
// during dev testing — a bogus reply once pushed the system clock to the year 343230). Without the upper
// bound, timeValid() would happily call that "synced" and every "now"/history-bucket read downstream would
// inherit the garbage value. 4102444800 = 2100-01-01 UTC — comfortably past any real deployment's lifetime.
static bool timeValid() { time_t t = time(nullptr); return t > 1735689600 && t < 4102444800; }


// Persistent per-reader logging to LittleFS, mounted on either store (see bootHistoryFS() below):
//   /s<id>  recent samples  "epoch,importWh,exportWh,powerW\n"  (ring buffer, capped -- see sampleCapBytes())
//   /d<id>  daily summary    "dayStartEpoch,importWh,exportWh\n" (one row per LOCAL calendar day)
// The /history page draws the cumulative kWh lines from the samples and — the headline the user
// asked for — the per-day consumption from the kWh-COUNTER deltas (day[i].import - day[i-1].import),
// because the Watt reading is not always sent by the meter and can't be trusted; Watt is only tabled.
// All file I/O runs on the web task (core 0), never on the LoRa loop.
#define HIST_SLOTS 64                   // must stay >= MAX_READERS (defined in main.cpp; it's an extern const,
                                        // so it can't size a static array here)
// No global price setting: every reader has its own (Reader.priceCentOverride/exportCentOverride in
// reader.h), editable from the History page's header once that reader is selected. These two literals are
// only the bootstrap default shown/used for a reader that has never had its own price saved yet -- see
// resolveReaderPrice() below.
static const float DEFAULT_PRICE_CENT = 31.0f, DEFAULT_EXPORT_CENT = 0.0f;
static uint32_t hImp[HIST_SLOTS];       // last-logged import per reader slot
static uint32_t hLastMs[HIST_SLOTS];    // millis() of last sample append (0 = nothing logged yet)
struct DailyState { uint32_t day = 0, imp = 0, exp = 0;
  uint32_t dayWh = 0, nightWh = 0;   // day/night 2-zone split so far (tariffMode==1), live by time-of-day --
                                      // see isNightNow()/historyService() below. Reset at each day rollover.
  uint32_t htWh = 0, stWh = 0, ntWh = 0;   // §14a HT/ST/NT 3-zone split so far (tariffMode==2), same idea --
                                            // see tariffZoneNow()/historyService() below. Mutually exclusive
                                            // with dayWh/nightWh above: a reader only ever feeds ONE pair,
                                            // matching its own tariffMode; the other stays 0.
  bool     haveStart = false;        // true once impStart/expStart below hold a real "start of today" value
                                      // (see beginDay()) -- false right after a reader's very first-ever
                                      // observation this boot, when no durable prior close is available yet,
                                      // same "nothing to backfill from" gap the History page's JS handles.
  uint32_t impStart = 0, expStart = 0;   // reader's import_/export_ at the moment TODAY began -- lets
                                          // readerTodayStats()/mqttService() report "today so far" without
                                          // any flash reads, unlike the History page's own equivalent calc.
};
static DailyState hDaily[HIST_SLOTS];   // current day and its latest observed counters

// Daily summaries ("/d<id>") always live in the 128 KB "userdata" partition, on every board -- they're
// tiny (rows are ~30 bytes) and matter for the long term, so they get the one storage location that's
// never resized, reformatted, or otherwise at risk from anything below. The partition's capacity is
// split fairly across however many readers currently have daily history -- not a fixed day count per
// reader -- so a lone reader gets (almost) the whole 128 KB (years of history) and adding a new reader
// automatically shrinks everyone's share on their next write, without needing a separate rebalance step.
// See dailyReaderCount()/dailyCapBytes() below.
// Raw samples ("/s<id>") go to the large, dynamically-sized OTA-tail store where supported (obi_gateway_c3,
// see ota_hist.h), falling back to the SAME "userdata" partition (i.e. no change from before this feature
// existed) on every other board, or if the OTA-tail mount fails for any reason.
// All history file I/O below goes through plain POSIX stdio (fopen/fread/...) rather than the Arduino
// LittleFS::File API, specifically so the SAME code works against either mount transparently -- the
// OTA-tail store is registered with the raw esp_vfs_littlefs_register() API (see ota_hist.cpp), which
// the Arduino LittleFS wrapper class has no way to target (it only ever mounts by partition label).
static String g_dailyBase = "/littlefs";
static String g_rawBase   = "/littlefs";

// Mount the 128 KB fallback store (also the permanent home for daily summaries). The partition table is
// fixed at the original serial flash and is NOT changed by OTA, so we can't rely on a "spiffs" label —
// this build's boards ship a "userdata" data partition instead. Try the known labels in order; the first
// that exists gets LittleFS (formatted on first use). The WiFi/MQTT config lives in the separate "nvs"
// partition, so formatting this is safe.
static bool mountFallbackFS() {
  static const char *labels[] = {"userdata", "spiffs", "storage", "littlefs", "ffat"};
  for (const char *l : labels) {
    if (esp_partition_find_first(ESP_PARTITION_TYPE_DATA, ESP_PARTITION_SUBTYPE_ANY, l) &&
        LittleFS.begin(true, "/littlefs", 5, l)) {
      Serial.printf("[web] history: LittleFS fallback on partition '%s' (128 KB)\n", l);
      return true;
    }
  }
  return false;
}

static bool bootHistoryFS() {
  bool dailyOk = mountFallbackFS();       // userdata -- ALWAYS the daily-summary home, and raw's fallback too
  g_dailyBase = "/littlefs";
  if (dailyOk && otaHist_mount()) {
    g_rawBase = OTA_HIST_BASE; g_usingOtaHist = true;   // raw samples get the big, growable OTA-tail store
    Serial.println("[web] history: raw samples on the OTA-tail store, daily summaries in userdata");
  } else {
    g_rawBase = "/littlefs"; g_usingOtaHist = false;    // everyone else: raw shares the 128 KB partition too
  }
  return dailyOk;
}

// Free/used space for the raw-sample store (the interesting, potentially large one) -- surfaced on the
// dashboard, /history, and (alongside dailySpace()) the /debug flash-map page.
static void historySpace(size_t &total, size_t &used) {
  total = used = 0;
  if (!g_fsOk) return;
  if (g_usingOtaHist) otaHist_space(total, used);
  else { total = LittleFS.totalBytes(); used = LittleFS.usedBytes(); }
}
// Free/used space for the daily-summary store (always userdata).
static void dailySpace(size_t &total, size_t &used) {
  total = used = 0;
  if (!g_fsOk) return;
  total = LittleFS.totalBytes(); used = LittleFS.usedBytes();
}

static String fpS(const String &id) { return g_rawBase + "/s" + id; }
static String fpD(const String &id) { return g_dailyBase + "/d" + id; }

static String fsRead(const String &path) {
  FILE *f = fopen(path.c_str(), "rb");
  if (!f) return String();
  String s; char buf[512]; size_t n;
  while ((n = fread(buf, 1, sizeof buf, f)) > 0) s.concat(buf, n);
  fclose(f);
  return s;
}
static bool fsWrite(const String &path, const String &data) {
  FILE *f = fopen(path.c_str(), "wb");
  if (!f) return false;
  size_t n = data.length();
  bool ok = (n == 0) || (fwrite(data.c_str(), 1, n, f) == n);
  fclose(f);
  return ok;
}

// Per-reader raw-sample file cap before compaction -- 5x larger on the OTA-tail store (many times the
// space of the 128 KB fallback, so it can actually hold "much longer" history rather than the same ~8 KB
// per reader sitting in a bigger-but-otherwise-unused partition).
static size_t sampleCapBytes()  { return g_usingOtaHist ? 40000 : 8000; }
static size_t sampleTrimBytes() { return g_usingOtaHist ? 25000 : 5000; }

// Append one line to `path`, then keep it bounded to capBytes (trim to trimBytes, snapped to a line
// boundary).
static void appendLineCapped(const String &path, const char *line, size_t capBytes, size_t trimBytes) {
  FILE *f = fopen(path.c_str(), "a");
  if (!f) return;
  fputs(line, f);
  long sz = ftell(f);
  fclose(f);
  if (sz > (long)capBytes) {
    String all = fsRead(path);
    int cut = (int)all.length() - (int)trimBytes;
    int nl  = all.indexOf('\n', cut > 0 ? cut : 0);
    if (nl >= 0) fsWrite(path, all.substring(nl + 1));
  }
}

// Append one sample line, then keep the file bounded (drop the oldest lines past the cap). No separate
// tail-mirror write here: on obi_gateway_c3, ota_hist.cpp's otaHist_prepareForFlash() instead takes a
// single fresh snapshot of the whole bulk store into the small OTA-survival reserve right before a flash
// starts -- fitting as much of the CURRENT data as possible (fair-shared across however many readers there
// are), rather than keeping a small fixed-size mirror continuously in sync on every single sample (wastes
// the reserve with few readers, and writes flash twice as often for no benefit between updates).
static void appendSample(const String &id, uint32_t ep, uint32_t imp, uint32_t exp, uint32_t pw) {
  char line[80];
  if (obi_na(pw)) snprintf(line, sizeof line, "%lu,%lu,%lu,\n",
                           (unsigned long)ep, (unsigned long)imp, (unsigned long)exp);
  else            snprintf(line, sizeof line, "%lu,%lu,%lu,%ld\n",   // power is signed (negative on feed-in)
                           (unsigned long)ep, (unsigned long)imp, (unsigned long)exp, (long)(int32_t)pw);
  appendLineCapped(fpS(id), line, sampleCapBytes(), sampleTrimBytes());
}

// How many readers currently need a slice of the daily-summary budget: every live (used) RAM slot, plus
// any reader that's gone quiet but still has a /d<id> file on flash (same "offline reader" cases the
// /history page already keeps reachable -- see handleHistoryReaders()). Deliberately NOT a config value:
// re-scanned on every call so it tracks reality the moment a reader is added, unbound, or its file is
// cleared -- no separate "rebalance" step needed anywhere.
static int dailyReaderCount() {
  String seen[HIST_SLOTS]; int n = 0;
  for (int i = 0; i < MAX_READERS && n < HIST_SLOTS; i++)
    if (readers[i].used) seen[n++] = hex(readers[i].handle, 3);
  if (g_fsOk) {
    DIR *dir = opendir(g_dailyBase.c_str());
    if (dir) {
      struct dirent *de;
      while ((de = readdir(dir)) != nullptr && n < HIST_SLOTS) {
        String name = de->d_name;
        if (name.length() != 7 || name[0] != 'd') continue;
        String id = name.substring(1);
        bool dup = false;
        for (int k = 0; k < n; k++) if (seen[k] == id) { dup = true; break; }
        if (!dup) seen[n++] = id;
      }
      closedir(dir);
    }
  }
  return n > 0 ? n : 1;
}

// Per-reader byte budget for the daily-summary log -- the userdata partition's whole capacity split evenly
// across however many readers dailyReaderCount() currently counts, NOT a fixed day count. A single reader
// gets (almost) the entire partition to itself (thousands of days -- rows are ~30 bytes each); the moment a
// second reader's first daily row is written, both share the partition roughly in half going forward, each
// trimming its oldest rows down to the new, smaller share on its own next write. No rebalance pass needed:
// every persistDaily() call recomputes this fresh, so the split just tracks however many readers exist now.
static size_t dailyCapBytes() {
  size_t total = 0, used = 0; dailySpace(total, used);
  if (!total) total = 131072;                    // partition not mounted yet -- assume the stock 128 KB
  size_t reserve = total / 8;                     // headroom for LittleFS's own metadata/wear-leveling
  size_t budget = total > reserve ? total - reserve : total;
  return budget / (size_t)dailyReaderCount();
}

// Return daily CSV with one row upserted. The same helper persists completed days and adds today's
// RAM-only row to API responses. `capBytes` is this reader's current fair share (see dailyCapBytes());
// trimming is byte-based (like appendLineCapped()'s raw-sample cap) rather than a fixed row count so it
// grows and shrinks smoothly as the reader count changes instead of jumping between fixed slot sizes.
static String withDailyRow(String all, uint32_t dayStart, uint32_t imp, uint32_t exp,
                            uint32_t dayWh, uint32_t nightWh,
                            uint32_t htWh, uint32_t stWh, uint32_t ntWh, size_t capBytes) {
  char row[110];
  snprintf(row, sizeof row, "%lu,%lu,%lu,%lu,%lu,%lu,%lu,%lu", (unsigned long)dayStart, (unsigned long)imp,
           (unsigned long)exp, (unsigned long)dayWh, (unsigned long)nightWh,
           (unsigned long)htWh, (unsigned long)stWh, (unsigned long)ntWh);
  String content;
  if (all.length() == 0) {
    content = String(row) + "\n";
  } else {
    int end = (int)all.length();
    if (all[end - 1] == '\n') end--;                     // ignore trailing newline
    int start = all.lastIndexOf('\n', end - 1) + 1;      // start index of the last line (0 if single line)
    uint32_t lastDay = strtoul(all.substring(start, end).c_str(), nullptr, 10);
    if (lastDay == dayStart) content = all.substring(0, start) + row + "\n";   // replace today's row
    else {
      content = all;
      if (content.length() && content[content.length() - 1] != '\n') content += "\n";
      content += String(row) + "\n";                     // a new day -> append
    }
  }
  // trim the oldest rows until back under this reader's current fair-share budget
  if (content.length() > capBytes) {
    int cut = (int)content.length() - (int)capBytes;
    int nl = content.indexOf('\n', cut > 0 ? cut : 0);
    content = (nl >= 0) ? content.substring(nl + 1) : String();
  }
  return content;
}

static void persistDaily(const String &id, uint32_t dayStart, uint32_t imp, uint32_t exp,
                          uint32_t dayWh, uint32_t nightWh, uint32_t htWh, uint32_t stWh, uint32_t ntWh) {
  String path = fpD(id);
  fsWrite(path, withDailyRow(fsRead(path), dayStart, imp, exp, dayWh, nightWh, htWh, stWh, ntWh, dailyCapBytes()));
}

static uint32_t localDayStart(time_t ep) {
  struct tm lt;
  localtime_r(&ep, &lt);
  lt.tm_hour = 0; lt.tm_min = 0; lt.tm_sec = 0;
  return (uint32_t)mktime(&lt);
}

// The [start,end) epoch bounds for the FTP export's currently-selected data window (g_ftpWindow) -- used by
// buildDailyCsv()/buildRawCsv() to filter rows, so a bounded preset produces a distinct, non-overlapping
// slice each run instead of always dumping everything currently on flash. start=0/end=UINT32_MAX means "no
// filtering" (preset 0, or the clock isn't synced yet and a wall-clock window can't be computed at all --
// safer to export everything than to silently apply a wrong window against a bad clock).
static void ftpWindowBounds(uint32_t &startEp, uint32_t &endEp) {
  startEp = 0; endEp = 0xFFFFFFFF;
  if (!timeValid()) return;
  uint32_t now = (uint32_t)time(nullptr);
  switch (g_ftpWindow) {
    case 1: startEp = now - 24UL * 3600; break;                                   // last 24h (rolling)
    case 2: endEp = localDayStart((time_t)now); startEp = endEp - 24UL * 3600; break;  // previous calendar day
    case 3: startEp = now - 7UL * 24 * 3600; break;                               // last 7 days (rolling)
    case 4: startEp = now - 30UL * 24 * 3600; break;                              // last 30 days (rolling)
    default: break;                                                               // 0 = everything stored
  }
}

// Recover the newest flash-backed sample after a reboot. If the gateway was down across midnight this
// is the best durable closing value for the previous day; during normal operation the RAM cache is newer.
static bool lastSample(const String &id, uint32_t &ep, uint32_t &imp, uint32_t &exp) {
  String all = fsRead(fpS(id));
  int end = (int)all.length();
  while (end > 0 && (all[end - 1] == '\n' || all[end - 1] == '\r')) end--;
  if (end == 0) return false;
  int start = all.lastIndexOf('\n', end - 1) + 1;
  unsigned long e, i, x;
  if (sscanf(all.substring(start, end).c_str(), "%lu,%lu,%lu", &e, &i, &x) != 3) return false;
  ep = (uint32_t)e; imp = (uint32_t)i; exp = (uint32_t)x;
  return true;
}

// Recover the last row ever PERSISTED to the daily-summary file -- unlike lastSample() above, this is only
// ever written at a genuine day rollover (see persistDaily()'s call sites), so it still holds the last
// *completed* day's closing counters even after a mid-day reboot has already appended today's entries to
// the raw sample log. That makes it the right fallback for beginDay()'s "reboot happened today, not
// overnight" case below.
static bool lastDailyRow(const String &id, uint32_t &dayStart, uint32_t &imp, uint32_t &exp) {
  String all = fsRead(fpD(id));
  int end = (int)all.length();
  while (end > 0 && (all[end - 1] == '\n' || all[end - 1] == '\r')) end--;
  if (end == 0) return false;
  int start = all.lastIndexOf('\n', end - 1) + 1;
  unsigned long d, i, x;
  if (sscanf(all.substring(start, end).c_str(), "%lu,%lu,%lu", &d, &i, &x) != 3) return false;
  dayStart = (uint32_t)d; imp = (uint32_t)i; exp = (uint32_t)x;
  return true;
}

// Finalize the previous day. After a reboot, recover the best durable closing value from the sample log
// if it belongs to an unfinished previous day. Today's row remains in RAM until its day is complete.
// Also captures impStart/expStart -- the reader's counters at the exact moment TODAY began -- wherever a
// genuinely reliable one is available, so readerTodayStats() can report "today so far" without touching
// flash on every MQTT publish. A reboot mid-day (the last stored sample is from TODAY, not a finished
// previous day) has no opening value in the sample log -- but the persisted daily-summary file is only
// ever written at a genuine rollover, so its last row is still the last *completed* day's close; fall back
// to that (lastDailyRow()) so haveStart comes back true right after THIS reboot too, not just at the next
// midnight. Only a reader with no history at all (nothing in either file yet) still starts with
// haveStart=false, same "nothing to backfill" gap the History page's own JS handles.
static void beginDay(int slot, const String &id, uint32_t dayStart) {
  DailyState &d = hDaily[slot];
  if (d.day == 0) {
    uint32_t oldEp, oldImp, oldExp;
    if (lastSample(id, oldEp, oldImp, oldExp)) {
      uint32_t oldDay = localDayStart((time_t)oldEp);
      // no day/night or HT/ST/NT split recoverable across a reboot gap -- the live accumulator that would
      // have tracked it started fresh this boot, same as every other in-RAM-only state
      if (oldDay != dayStart) {
        persistDaily(id, oldDay, oldImp, oldExp, 0, 0, 0, 0, 0);
        d.impStart = oldImp; d.expStart = oldExp; d.haveStart = true;   // genuine previous-day close
      } else {
        // mid-day reboot -- the sample log's newest entry is already from today. Recover the last
        // COMPLETED day's closing counters from the daily-summary file instead.
        uint32_t pDay, pImp, pExp;
        if (lastDailyRow(id, pDay, pImp, pExp) && pDay != dayStart) {
          d.impStart = pImp; d.expStart = pExp; d.haveStart = true;
        } else {
          d.haveStart = false;   // no completed-day close on record either -- truly nothing to start from
        }
      }
    } else {
      d.haveStart = false;     // no prior sample at all -- brand new reader
    }
  } else {
    d.impStart = d.imp; d.expStart = d.exp; d.haveStart = true;   // yesterday's closing value, captured
                                                                    // before persistDaily's read-modify-write
                                                                    // below (which doesn't touch d.imp/d.exp)
    persistDaily(id, d.day, d.imp, d.exp, d.dayWh, d.nightWh, d.htWh, d.stWh, d.ntWh);
  }
  d.day = dayStart;
  d.dayWh = 0; d.nightWh = 0;              // start the new day's live day/night split fresh
  d.htWh = 0; d.stWh = 0; d.ntWh = 0;      // ...and the live HT/ST/NT split fresh
}

// Is hour `h` (0-23) inside the [s,e) window? A degenerate window (s==e) is "unused"/always false -- shared
// convention for every hour-window field in this file (nightStartHour/nightEndHour, htStart/htEnd,
// ntStart/ntEnd). Wraps past midnight when s >= e (e.g. 22..6 means "22:00 through 05:59").
static bool inHourWindow(uint8_t s, uint8_t e, int h) {
  if (s == e) return false;
  return s < e ? (h >= s && h < e) : (h >= s || h < e);
}

// Is `now` inside reader `r`'s configured night window? Off (always "day") unless nightTariffOn.
static bool isNightNow(const Reader &r, time_t now) {
  if (!r.nightTariffOn) return false;
  struct tm lt; localtime_r(&now, &lt);
  return inHourWindow(r.nightStartHour, r.nightEndHour, lt.tm_hour);
}

// Which §14a Modul-3 zone `now` falls into for reader `r` (tariffMode==2 only -- caller checks that).
// HT is checked before NT, so a misconfigured overlap resolves to the (usually pricier) HT zone rather than
// silently favoring NT; ST is the fallback for "in neither window", exactly like the day rate is "not in the
// night window" above.
enum TariffZone : uint8_t { ZONE_ST = 0, ZONE_HT = 1, ZONE_NT = 2 };
static TariffZone tariffZoneNow(const Reader &r, time_t now) {
  struct tm lt; localtime_r(&now, &lt);
  int h = lt.tm_hour;
  for (int i = 0; i < 2; i++) if (inHourWindow(r.htStart[i], r.htEnd[i], h)) return ZONE_HT;
  for (int i = 0; i < 2; i++) if (inHourWindow(r.ntStart[i], r.ntEnd[i], h)) return ZONE_NT;
  return ZONE_ST;
}

// Short machine-readable name for whatever zone reader `r` is in right now, across all three tariff
// schemes -- used by MQTT/HA (a single "current zone" sensor covers every reader regardless of its mode)
// and mirrors the labels used in the History page settings card 1:1.
static const char *tariffZoneName(const Reader &r, time_t now) {
  if (r.tariffMode == 2) {
    switch (tariffZoneNow(r, now)) {
      case ZONE_HT: return "ht";
      case ZONE_NT: return "nt";
      default:      return "st";
    }
  }
  if (r.tariffMode == 1) return isNightNow(r, now) ? "night" : "day";
  return "flat";
}

// The ct/kWh rate actually billed for reader `r` right now, whichever scheme is active -- the single
// number a "current price" MQTT/HA sensor needs, without the subscriber having to know which scheme or do
// its own zone lookup.
static float tariffRateCentNow(const Reader &r, time_t now) {
  float price = r.priceCentOverride >= 0 ? r.priceCentOverride : DEFAULT_PRICE_CENT;
  if (r.tariffMode == 2) {
    switch (tariffZoneNow(r, now)) {
      case ZONE_HT: return r.htPriceCent >= 0 ? r.htPriceCent : price;
      case ZONE_NT: return r.ntPriceCent >= 0 ? r.ntPriceCent : price;
      default:      return price;
    }
  }
  if (r.tariffMode == 1 && isNightNow(r, now))
    return r.nightPriceCent >= 0 ? r.nightPriceCent : price;
  return price;
}

// Today's consumption/export/cost/earnings for reader `r` (RAM slot `slot`, same index as readers[]/
// hDaily[]) -- the server-side equivalent of the History page's own JS KPI calc (see load() there), so
// MQTT/HA can show the same numbers without a browser. False (all outputs untouched) if there's no
// reliable "start of today" baseline yet -- see haveStart in DailyState/beginDay().
static bool readerTodayStats(int slot, const Reader &r, float &todayWh, float &todayExpWh,
                              float &todayCostEur, float &todayEarnEur) {
  const DailyState &d = hDaily[slot];
  if (!d.haveStart) return false;
  todayWh    = d.imp > d.impStart ? (float)(d.imp - d.impStart) : 0.0f;
  todayExpWh = d.exp > d.expStart ? (float)(d.exp - d.expStart) : 0.0f;
  float price      = r.priceCentOverride  >= 0 ? r.priceCentOverride  : DEFAULT_PRICE_CENT;
  float exportCent = r.exportCentOverride >= 0 ? r.exportCentOverride : DEFAULT_EXPORT_CENT;
  if (r.tariffMode == 2) {
    float ht = r.htPriceCent >= 0 ? r.htPriceCent : price;
    float nt = r.ntPriceCent >= 0 ? r.ntPriceCent : price;
    todayCostEur = (d.htWh / 1000.0f) * (ht / 100.0f) + (d.stWh / 1000.0f) * (price / 100.0f) +
                   (d.ntWh / 1000.0f) * (nt / 100.0f);
  } else if (r.tariffMode == 1) {
    float np = r.nightPriceCent >= 0 ? r.nightPriceCent : price;
    todayCostEur = (d.dayWh / 1000.0f) * (price / 100.0f) + (d.nightWh / 1000.0f) * (np / 100.0f);
  } else {
    todayCostEur = (todayWh / 1000.0f) * (price / 100.0f);
  }
  todayEarnEur = (todayExpWh / 1000.0f) * (exportCent / 100.0f);
  return true;
}

// Poll readers and log a sample when the counter moves or every 5 min (heartbeat). Throttled internally.
// Also accumulates each reader's day/night energy split live, hour-by-hour, as the ONLY point in the
// pipeline that ever sees consumption tagged with a real time-of-day -- the raw sample log this could
// otherwise be reconstructed from is short-retention, so this can't be done retroactively later.
static void historyService() {
  if (!g_fsOk || !timeValid() || otaHist_writesPaused()) return;   // paused around a firmware flash --
                                                                     // see otaHist_prepareForFlash()
  static uint32_t lastPoll = 0;
  uint32_t now = millis();
  if (now - lastPoll < 1000) return;
  lastPoll = now;
  time_t tnow = time(nullptr);
  uint32_t dayStart = localDayStart(tnow);
  for (int i = 0; i < MAX_READERS; i++) {
    Reader &r = readers[i];
    if (!r.used || !r.haveData || obi_na(r.import_)) continue;
    String id;
    uint32_t exp = obi_na(r.export_) ? 0 : r.export_;
    if (hDaily[i].day != dayStart) {
      id = hex(r.handle, 3);
      beginDay(i, id, dayStart);   // also resets dayWh/nightWh for the new day
    } else if (hDaily[i].imp) {    // not the first-ever observation this boot -- imp already a real baseline
      long delta = (long)r.import_ - (long)hDaily[i].imp;   // Wh since the last poll; counters only rise
      if (delta > 0) {
        if (r.tariffMode == 2) {
          switch (tariffZoneNow(r, tnow)) {
            case ZONE_HT: hDaily[i].htWh += (uint32_t)delta; break;
            case ZONE_NT: hDaily[i].ntWh += (uint32_t)delta; break;
            default:      hDaily[i].stWh += (uint32_t)delta; break;
          }
        } else if (isNightNow(r, tnow)) hDaily[i].nightWh += (uint32_t)delta;
        else                            hDaily[i].dayWh   += (uint32_t)delta;
      }
    }
    hDaily[i].imp = r.import_;
    hDaily[i].exp = exp;
    bool firstLog  = (hLastMs[i] == 0);
    bool changed   = (r.import_ != hImp[i]);
    bool heartbeat = (now - hLastMs[i] >= 5UL * 60 * 1000);
    if (!(firstLog || changed || heartbeat)) continue;
    if (!firstLog && (now - hLastMs[i] < 30000)) continue;   // min 30 s spacing between samples
    if (!id.length()) id = hex(r.handle, 3);
    appendSample(id, (uint32_t)tnow, r.import_, exp, r.power);   // exp, not r.export_ -- a void export must
                                                                  // never leak its raw sentinel into the log
    hImp[i] = r.import_; hLastMs[i] = now;
  }
}

// Stream a CSV blob as a JSON array-of-arrays (empty field -> null), chunked to keep RAM low.
static void streamRows(const String &csv) {
  int i = 0, n = (int)csv.length(); bool firstRow = true;
  String chunk; chunk.reserve(1600);
  while (i < n) {
    int nl = csv.indexOf('\n', i); if (nl < 0) nl = n;
    String line = csv.substring(i, nl); line.trim(); i = nl + 1;
    if (!line.length()) continue;
    // Sanity-bound the epoch (always the first column, for both samples and daily rows) — same range as
    // timeValid(). Drops rows written while the system clock was corrupted (e.g. a failed mktime() call
    // returning -1, which cast to uint32_t reads back as 4294967295 = 2106-02-07) so a single old poisoned
    // row already on flash can't wreck a chart's x-axis scale forever — new writes are already gated by
    // timeValid() in historyService(), this just also protects reads of whatever was written before that.
    { int fc = line.indexOf(',');
      unsigned long ep = strtoul((fc < 0 ? line : line.substring(0, fc)).c_str(), nullptr, 10);
      if (ep <= 1735689600UL || ep >= 4102444800UL) continue; }
    String row = firstRow ? "[" : ",["; firstRow = false;
    int fs = 0, col = 0;
    for (int k = 0; k <= (int)line.length(); k++) {
      if (k == (int)line.length() || line[k] == ',') {
        String f = line.substring(fs, k); fs = k + 1;
        if (col) row += ",";
        row += f.length() ? f : String("null");
        col++;
      }
    }
    row += "]";
    chunk += row;
    if (chunk.length() > 1400) { server.sendContent(chunk); chunk = ""; }
  }
  if (chunk.length()) server.sendContent(chunk);
}

// /api/history/readers — every 6-hex reader id that has a /s<id> or /d<id> log on flash, live or not.
// The dashboard's live reader list (/api/readers) only knows readers that have announced themselves since
// boot -- one that's out of range (or permanently removed) never gets a RAM slot back, so without this a
// reader with months of stored history becomes both unviewable and undeletable the moment it goes quiet.
// The /history page merges this into its selector so "gone" readers stay reachable for exactly that: look
// at their last data, or clear their old files.
static void handleHistoryReaders() {
  String j = "[";
  bool first = true;
  if (g_fsOk) {
    String seen[HIST_SLOTS]; int nSeen = 0;
    // Scan both stores -- daily and raw usually live in different places now (userdata vs. the OTA-tail
    // store), but fall back to the SAME directory on non-C3 boards; skip the second scan then.
    String bases[2] = { g_dailyBase, g_rawBase };
    int nBases = (g_dailyBase == g_rawBase) ? 1 : 2;
    for (int b = 0; b < nBases; b++) {
      DIR *dir = opendir(bases[b].c_str());
      if (!dir) continue;
      struct dirent *de;
      while ((de = readdir(dir)) != nullptr) {
        String name = de->d_name;   // bare filename, no mountpoint/path prefix
        if (name.length() == 7 && (name[0] == 's' || name[0] == 'd')) {
          String id = name.substring(1);
          bool okid = true;
          for (size_t k = 0; k < 6; k++) {
            char c = id[k];
            if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f'))) { okid = false; break; }
          }
          bool dup = false;
          for (int k = 0; k < nSeen; k++) if (seen[k] == id) { dup = true; break; }
          if (okid && !dup) {
            if (nSeen < HIST_SLOTS) seen[nSeen++] = id;
            j += (first ? "" : ",") + jstr(id.c_str());
            first = false;
          }
        }
      }
      closedir(dir);
    }
  }
  j += "]";
  server.send(200, "application/json", j);
}

// Resolve the effective price for reader `id`: its own saved value, else the bootstrap default (no global
// setting exists -- every reader's price is independent). Also resolves the day-night tariff fields (off,
// with sane defaults, if the reader isn't known or has it off), and the §14a HT/ST/NT tariff fields
// (tariffMode/htPrice/ntPrice -- the window times themselves aren't needed here, only in readersJson() for
// the settings-card prefill; the cost calc only needs the per-day htWh/stWh/ntWh split plus these 3 prices).
static void resolveReaderPrice(const String &id, float &priceCent, float &exportCent,
                                bool &nightOn, uint8_t &nightStart, uint8_t &nightEnd, float &nightPriceCent,
                                uint8_t &tariffMode, float &htPriceCent, float &ntPriceCent) {
  priceCent = DEFAULT_PRICE_CENT; exportCent = DEFAULT_EXPORT_CENT;
  nightOn = false; nightStart = 22; nightEnd = 6; nightPriceCent = DEFAULT_PRICE_CENT;
  tariffMode = 0; htPriceCent = DEFAULT_PRICE_CENT; ntPriceCent = DEFAULT_PRICE_CENT;
  for (int i = 0; i < MAX_READERS; i++)
    if (readers[i].used && hex(readers[i].handle, 3) == id) {
      Reader &r = readers[i];
      if (r.priceCentOverride >= 0) priceCent = r.priceCentOverride;
      if (r.exportCentOverride >= 0) exportCent = r.exportCentOverride;
      nightOn = r.nightTariffOn; nightStart = r.nightStartHour; nightEnd = r.nightEndHour;
      nightPriceCent = r.nightPriceCent >= 0 ? r.nightPriceCent : priceCent;
      tariffMode = r.tariffMode;
      htPriceCent = r.htPriceCent >= 0 ? r.htPriceCent : priceCent;
      ntPriceCent = r.ntPriceCent >= 0 ? r.ntPriceCent : priceCent;
      break;
    }
}

static void handleHistoryApi() {
  String id = server.arg("id");
  bool okid = id.length() == 6;
  if (okid) for (size_t k = 0; k < 6; k++) {
    char c = id[k];
    if (!((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f') || (c >= 'A' && c <= 'F'))) { okid = false; break; }
  }
  if (!okid) { server.send(400, "application/json", "{\"err\":\"id\"}"); return; }
  id.toLowerCase();
  server.setContentLength(CONTENT_LENGTH_UNKNOWN);
  server.sendHeader("Cache-Control", "no-store");
  server.send(200, "application/json", "");
  bool tv = timeValid();   // gate "now" itself too — the client uses it for day-bucketing ("today" match);
                            // an out-of-range clock (see timeValid()) must never leak into that as if real.
  float priceCent, exportCent, nightPriceCent, htPriceCent, ntPriceCent;
  bool nightOn; uint8_t nightStart, nightEnd, tariffMode;
  resolveReaderPrice(id, priceCent, exportCent, nightOn, nightStart, nightEnd, nightPriceCent,
                     tariffMode, htPriceCent, ntPriceCent);
  server.sendContent(String("{\"id\":\"") + id + "\",\"now\":" + String(tv ? (uint32_t)time(nullptr) : 0) +
                     ",\"tvalid\":" + (tv ? "true" : "false") +
                     ",\"fs\":" + (g_fsOk ? "true" : "false") +
                     ",\"price\":" + String(priceCent, 2) +
                     ",\"eprice\":" + String(exportCent, 2) +
                     ",\"night_on\":" + (nightOn ? "true" : "false") +
                     ",\"night_start\":" + String(nightStart) + ",\"night_end\":" + String(nightEnd) +
                     ",\"night_price\":" + String(nightPriceCent, 2) +
                     ",\"tariff_mode\":" + String(tariffMode) +
                     ",\"ht_price\":" + String(htPriceCent, 2) +
                     ",\"nt_price\":" + String(ntPriceCent, 2) + ",\"samples\":[");
  { String s = g_fsOk ? fsRead(fpS(id)) : String(); streamRows(s); }
  server.sendContent("],\"daily\":[");
  {
    String d = g_fsOk ? fsRead(fpD(id)) : String();
    for (int i = 0; i < MAX_READERS; i++)
      if (hDaily[i].day && readers[i].used && hex(readers[i].handle, 3) == id) {
        d = withDailyRow(d, hDaily[i].day, hDaily[i].imp, hDaily[i].exp, hDaily[i].dayWh, hDaily[i].nightWh,
                        hDaily[i].htWh, hDaily[i].stWh, hDaily[i].ntWh, dailyCapBytes());
        break;
      }
    streamRows(d);
  }
  server.sendContent("]}");
  server.sendContent("");                                // terminate the chunked response
}

static String isoLocal(time_t ep) {
  struct tm lt; localtime_r(&ep, &lt);
  char b[24]; strftime(b, sizeof b, "%Y-%m-%d %H:%M:%S", &lt);
  return String(b);
}

// Build the daily CSV for one reader (same content handleHistoryCsv's kind=daily download produces), as a
// plain in-memory String rather than streamed to an HTTP response -- used by the periodic FTP upload below.
// Daily logs stay small even after years (see ota_hist.h), so building the whole thing in RAM first is fine
// here (unlike the raw/sample log, which the HTTP download path keeps chunked instead).
static String buildDailyCsv(const String &id) {
  if (!g_fsOk) return String();
  String d = fsRead(fpD(id));
  for (int i = 0; i < MAX_READERS; i++)
    if (hDaily[i].day && readers[i].used && hex(readers[i].handle, 3) == id) {
      d = withDailyRow(d, hDaily[i].day, hDaily[i].imp, hDaily[i].exp, hDaily[i].dayWh, hDaily[i].nightWh,
                        hDaily[i].htWh, hDaily[i].stWh, hDaily[i].ntWh, dailyCapBytes());
      break;
    }
  String out = "date,day_start_epoch,import_wh,export_wh,day_wh,night_wh,ht_wh,st_wh,nt_wh\n";
  int i = 0, n = (int)d.length();
  while (i < n) {
    int nl = d.indexOf('\n', i); if (nl < 0) nl = n;
    String line = d.substring(i, nl); line.trim(); i = nl + 1;
    if (!line.length()) continue;
    int fc = line.indexOf(',');
    unsigned long ep = strtoul((fc < 0 ? line : line.substring(0, fc)).c_str(), nullptr, 10);
    if (ep <= 1735689600UL || ep >= 4102444800UL) continue;   // same epoch sanity bound as sendCsvRows()
    if (ep < g_ftpWinStart || ep >= g_ftpWinEnd) continue;    // outside the FTP export's selected window (see ftpWindowBounds())
    out += isoLocal((time_t)ep); out += ","; out += line; out += "\n";
  }
  return out;
}


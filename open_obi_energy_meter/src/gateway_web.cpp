// Point PubSubClient at the plain or TLS socket per g_mqttTls, then (re)set the broker address.
// With a CA cert we verify the broker; without one we only encrypt (setInsecure) — fine for a self-signed
// broker on the LAN (e.g. the project's own mqtts_server.py). Call after any host/port/TLS change.
//
// Short, explicit timeouts on both clients: mqttService()'s mqtt.connect() runs on webTask, the SAME task
// that also serves the whole web UI (server.handleClient()) — see the comment near mqttService(). Left at
// library defaults, a TLS/port mismatch (e.g. "MQTTS" left unchecked against a TLS-only broker, or checked
// against a plaintext one) blocks that shared task for MQTT_SOCKET_TIMEOUT (15 s, PubSubClient) or, far
// worse, WiFiClientSecure's default TLS handshake_timeout of 120 s — during which the ENTIRE dashboard is
// unresponsive, and it repeats on every retry until the config is fixed. 5 s is generous for a real broker
// on the LAN/internet and turns a 2-minute freeze into a brief, tolerable one.
static void applyMqttClient() {
  netTls.setTimeout(5);            // TCP connect budget for the TLS socket
  netTls.setHandshakeTimeout(5);   // TLS handshake budget (library default: 120 s)
  net.setTimeout(5);               // TCP connect budget for the plain socket
  mqtt.setSocketTimeout(5);        // PubSubClient's own read timeout while waiting for CONNACK etc. (default: 15 s)
  if (g_mqttTls) {
    if (g_mqttCa.length()) netTls.setCACert(g_mqttCa.c_str());
    else                   netTls.setInsecure();     // encrypt only, don't validate the cert chain
    mqtt.setClient(netTls);
  } else {
    mqtt.setClient(net);
  }
  mqtt.setServer(g_mqttHost, g_mqttPort);
}

